def rows(*lines: str) -> tuple[int, ...]:
    if len(lines) != 7 or any(len(line) != 5 for line in lines):
        raise ValueError("a text glyph must contain seven 5-pixel rows")
    return tuple(sum((1 << (6 - x)) for x, dot in enumerate(line) if dot == "#") for line in lines) + (0,)


