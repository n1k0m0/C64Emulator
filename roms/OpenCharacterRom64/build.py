def graphic(code: int) -> tuple[int, ...]:
    """Draw PET-style line/block graphics without importing existing ROM art."""
    index = code - 64
    pixels = [[False] * 8 for _ in range(8)]

    def fill(x0: int, y0: int, x1: int, y1: int) -> None:
        for y in range(y0, y1):
            for x in range(x0, x1):
                pixels[y][x] = True

    if index == 0:
        # The first graphics code is a usable horizontal rule.
        fill(0, 3, 8, 5)
    elif index < 16:
        # Line segments and junctions in the first graphics page.
        if index & 1:
            fill(3, 0, 5, 8)
        if index & 2:
            fill(0, 3, 8, 5)
        if index & 4:
            fill(0, 0, 2, 4)
        if index & 8:
            fill(6, 4, 8, 8)
    elif index < 32:
        # Outlines, crosses, circles, and filled bars.
        kind = index - 16
        if kind == 0:
            # A fine outlined ring keeps this graphics position visible.
            fill(2, 1, 6, 2)
            fill(1, 2, 2, 6)
            fill(6, 2, 7, 6)
            fill(2, 6, 6, 7)
        if kind & 1:
            fill(1, 1, 7, 2)
            fill(1, 6, 7, 7)
        if kind & 2:
            fill(1, 1, 2, 7)
            fill(6, 1, 7, 7)
        if kind & 4:
            for y in range(1, 7):
                pixels[y][y] = True
                pixels[y][7 - y] = True
        if kind & 8:
            fill(2, 2, 6, 6)
    elif index < 48:
        # Full/partial block elements, useful for bar charts and box drawings.
        kind = index - 32
        if kind & 1:
            fill(0, 0, 4, 8)
        if kind & 2:
            fill(4, 0, 8, 8)
        if kind & 4:
            fill(0, 0, 8, 4)
        if kind & 8:
            fill(0, 4, 8, 8)
    else:
        kind = index - 48
        # Quarter blocks and fine horizontal/vertical bars.
        if kind == 0:
            # Sparse stipple distinct from the intentionally blank spaces.
            for y in (1, 3, 5):
                for x in (1, 3, 5):
                    pixels[y][x] = True
        if kind & 1:
            fill(0, 0, 4, 4)
        if kind & 2:
            fill(4, 0, 8, 4)
        if kind & 4:
            fill(0, 4, 4, 8)
        if kind & 8:
            fill(4, 4, 8, 8)
    return tuple(sum(1 << (7 - x) for x, on in enumerate(row) if on) for row in pixels)


def base_glyph(code: int, lower_case: bool) -> tuple[int, ...]:
    if code == 0:
        return FONT["@"]
    if 1 <= code <= 26:
        letter = chr(ord("A") + code - 1)
        return FONT[letter.lower() if lower_case else letter]
    if 27 <= code <= 31:
        return FONT["[£]↑←"[code - 27]]
    if 32 <= code <= 63:
        return FONT[chr(code)]
    if lower_case and 65 <= code <= 90:
        return FONT[chr(code)]
    if code == 96:
        return FONT[" "]
    return graphic(code)


def build() -> bytes:
    output = bytearray()
    for lower_case in (False, True):
        glyphs = [base_glyph(code, lower_case) for code in range(128)]
        missing = [code for code, glyph in enumerate(glyphs)
                   if code not in (32, 96) and not any(glyph)]
        if missing:
            raise ValueError(f"unassigned visible screen codes: {missing}")
        for glyph in glyphs:
            output.extend(glyph)
        for glyph in glyphs:
            output.extend(byte ^ 0xFF for byte in glyph)
    assert len(output) == 4096
    return bytes(output)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path, help="output 4096-byte ROM image")
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(build())
    print(f"Open Character Rom 64: {args.output} (4096 bytes)")


if __name__ == "__main__":
    main()
